import type { AddonFileConfiguration } from '@ogi-sdk/executor';
import { Data, Effect } from 'effect';
import { OGIConfig } from './configure';

export class CompilerError extends Data.TaggedError('CompilerError') {
  message: string;
  constructor(message: string) {
    super();
    this.message = message;
  }
}
export class CompileAddonJSON {
  ogiConfig: OGIConfig;

  constructor(ogiConfig: OGIConfig) {
    this.ogiConfig = ogiConfig;
  }

  // `--write` is reserved for writing files besides addon.json, which nothing does yet
  compile(_allowedWriting: boolean) {
    return Effect.gen(this, function* () {
      if (!this.ogiConfig.compile)
        return yield* Effect.fail(
          new CompilerError('ogi.config.js does not declare compile.')
        );

      // schema types are readonly, so build the addon.json rather than mutate it
      const scripts: AddonFileConfiguration['scripts'] = {
        // the app appends --addonPort/--addonSecret, which `--` passes through to the script
        run: 'bun ogi run launch --',
        preSetup: this.ogiConfig.scripts.preSetup
          ? 'bun ogi run preSetup'
          : undefined,
        postSetup: this.ogiConfig.scripts.postSetup
          ? 'bun ogi run postSetup'
          : undefined,
        setup: this.ogiConfig.scripts.setup ? 'bun ogi run setup' : undefined,
      };
      const icon: AddonFileConfiguration['icon'] = this.ogiConfig.iconPath;
      let completeJSON = JSON.stringify(
        {
          _:
            'AUTO-GENERATED BY OGI-KIT ON ' +
            new Date().toISOString() +
            '. DO NOT EDIT, YOUR CHANGES WILL BE OVERWRITTEN.',
          scripts,
          author: this.ogiConfig.author,
          icon,
        } as Partial<AddonFileConfiguration>,
        null,
        2
      );

      return completeJSON satisfies string;
    });
  }
}
